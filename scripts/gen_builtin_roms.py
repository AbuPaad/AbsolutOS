#!/usr/bin/env python3
"""Generate src/games/BuiltinRoms.generated.h from assets/roms/.

The firmware ships Celeste (PICO-8) and Tetris (Game Boy) inside the app image so
a freshly flashed unit has games without a portal upload. The bytes live in
flash as const arrays; src/games/BuiltinRoms.cpp copies them into LittleFS the
first time the Games app opens, so the existing /roms scan and loaders are used
unchanged.

Run:  python3 scripts/gen_builtin_roms.py
Check: python3 scripts/gen_builtin_roms.py --check   (fails on drift)

Never hand-edit the generated header: change an asset here and regenerate.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets" / "roms"
OUT = ROOT / "src" / "games" / "BuiltinRoms.generated.h"


def find(name: str, *globs: str) -> Path:
    for pattern in (name, *globs):
        for path in ASSETS.rglob(pattern):
            if path.is_file():
                return path
    raise SystemExit(f"missing asset: {name} under {ASSETS}")


def c_array(data: bytes, indent: str = "    ", per_line: int = 16) -> str:
    lines = []
    for offset in range(0, len(data), per_line):
        chunk = data[offset:offset + per_line]
        lines.append(indent + "".join(f"0x{byte:02x}," for byte in chunk))
    return "\n".join(lines)


def render() -> str:
    celeste = find("celeste.p8.png", "*.p8.png")
    tetris = find("tetris.gb", "*.gb")
    celeste_bytes = celeste.read_bytes()
    tetris_bytes = tetris.read_bytes()

    return f"""// AUTO-GENERATED by scripts/gen_builtin_roms.py - DO NOT EDIT.
//
// Embedded game images: the bytes below are compiled into the app image and
// copied to LittleFS by src/games/BuiltinRoms.cpp when the file is missing.
//
//   {celeste.relative_to(ROOT)}  ({len(celeste_bytes)} bytes)
//   {tetris.relative_to(ROOT)}  ({len(tetris_bytes)} bytes)
//
// Regenerate: python3 scripts/gen_builtin_roms.py
// Drift gate: python3 scripts/gen_builtin_roms.py --check

#pragma once

#include <cstddef>
#include <cstdint>

namespace numos::games::builtin {{

inline constexpr const char* kCelestePath = "/roms/pico8/celeste.p8.png";
inline constexpr uint32_t kCelesteBytes = {len(celeste_bytes)}u;
inline constexpr unsigned char kCelesteImage[kCelesteBytes] = {{
{c_array(celeste_bytes)}
}};

inline constexpr const char* kTetrisPath = "/roms/gb/tetris.gb";
inline constexpr uint32_t kTetrisBytes = {len(tetris_bytes)}u;
inline constexpr unsigned char kTetrisImage[kTetrisBytes] = {{
{c_array(tetris_bytes)}
}};

}}  // namespace numos::games::builtin
"""


def main() -> int:
    rendered = render()
    check = "--check" in sys.argv[1:]
    if check:
        if not OUT.exists():
            print(f"FAIL {OUT.relative_to(ROOT)}: missing")
            return 1
        if OUT.read_text() != rendered:
            print(f"FAIL {OUT.relative_to(ROOT)}: drifted from assets/roms/")
            print("     run: python3 scripts/gen_builtin_roms.py")
            return 1
        print(f"OK {OUT.relative_to(ROOT)} matches assets/roms/")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rendered)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
