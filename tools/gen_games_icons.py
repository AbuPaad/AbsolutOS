#!/usr/bin/env python3
"""Generate LVGL A8 (alpha-only) icon descriptors from the owner's pixel art.

Sources (owner-supplied, /home/fih/Downloads):
  pixel--globe.png, pixel--folder.png           32x32, black ink + alpha
  pixel--ellipses-horizontal-circle.svg         24x24 pixel paths, currentColor

Output: src/ui/games/GamesIcons.c — one lv_image_dsc_t per icon, A8 so the app
recolours them with image_recolor (no second copy per theme).
"""
import re
import sys
from PIL import Image, ImageDraw, ImageChops

DL = "/home/fih/Downloads/"
OUT = "src/ui/games/GamesIcons.c"
SIZE = 64   # owner-supplied PNGs are 64x64: store at native, draw 1:1


def alpha_from_png(path):
    """Binary alpha: the owner's PNGs are antialiased, and a soft grey fringe on a
    320x156 panel reads as blur. Thresholding keeps the pixel-art edge."""
    im = Image.open(path).convert("RGBA")
    a = im.getchannel("A").point(lambda v: 255 if v >= 128 else 0)
    if a.size != (SIZE, SIZE):
        a = a.resize((SIZE, SIZE), Image.NEAREST)
    return a


def raster_svg(path, grid=24):
    """Rasterise pixel-art SVG strokes.

    These icons are drawn as 1-unit-wide rectilinear strokes, so the ink is the
    set of unit cells the path walks through — not the filled interior. Marking
    visited cells reproduces the art exactly (a ring stays a ring)."""
    src = open(path, encoding="utf-8").read()
    # Skip fill="none" elements: the art ships a transparent 24x24 bounding box
    # as its first path, and stroking it would draw a frame round the icon.
    paths = []
    for el in re.findall(r"<path\b[^>]*>", src):
        if 'fill="none"' in el:
            continue
        m = re.search(r'\bd="([^"]+)"', el)
        if m:
            paths.append(m.group(1))
    cells = set()
    for d in paths:
        toks = re.findall(r"[MmLlHhVvZz]|-?\d+\.?\d*", d)
        i = 0
        cur = [0.0, 0.0]
        start = [0.0, 0.0]

        def mark(x, y):
            xi, yi = int(round(x)), int(round(y))
            if 0 <= xi < grid and 0 <= yi < grid:
                cells.add((xi, yi))

        def walk(x0, y0, x1, y1):
            steps = int(max(abs(x1 - x0), abs(y1 - y0)))
            for s in range(steps + 1):
                t = 0 if steps == 0 else s / steps
                mark(x0 + (x1 - x0) * t, y0 + (y1 - y0) * t)

        while i < len(toks):
            t = toks[i]
            if t in "MmLl":
                i += 1
                x, y = float(toks[i]), float(toks[i + 1]); i += 2
                if t == "m":
                    x, y = cur[0] + x, cur[1] + y
                cur = [x, y]; start = [x, y]
                mark(x, y)
            elif t in "Hh":
                i += 1
                x = float(toks[i]); i += 1
                x = cur[0] + x if t == "h" else x
                walk(cur[0], cur[1], x, cur[1]); cur[0] = x
            elif t in "Vv":
                i += 1
                y = float(toks[i]); i += 1
                y = cur[1] + y if t == "v" else y
                walk(cur[0], cur[1], cur[0], y); cur[1] = y
            elif t in "Zz":
                i += 1
                walk(cur[0], cur[1], start[0], start[1]); cur = list(start)
            else:
                i += 1

    img = Image.new("L", (grid, grid), 0)
    px = img.load()
    for (x, y) in cells:
        px[x, y] = 255
    return img


def emit(name, mask):
    mask = mask.resize((SIZE, SIZE), Image.NEAREST)
    data = list(mask.tobytes())
    rows = []
    for y in range(SIZE):
        row = data[y * SIZE:(y + 1) * SIZE]
        rows.append("    " + ",".join(str(v) for v in row) + ",")
    body = "\n".join(rows)
    return (
        f"static const uint8_t ic_{name}_alpha[{SIZE * SIZE}] = {{\n{body}\n}};\n\n"
        f"const lv_image_dsc_t ic_{name} = {{\n"
        f"    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8,\n"
        f"                .flags = 0, .w = {SIZE}, .h = {SIZE}, .stride = {SIZE} }},\n"
        f"    .data_size = {SIZE * SIZE},\n"
        f"    .data = ic_{name}_alpha,\n"
        f"}};\n"
    )


def main():
    icons = [
        ("globe", alpha_from_png(DL + "pixel--globe(1).png")),
        ("folder", alpha_from_png(DL + "pixel--folder(1).png")),
        ("more", alpha_from_png(DL + "pixel--ellipses-horizontal-circle.png")),
    ]
    out = [
        "/* Generated by tools/gen_games_icons.py — do not hand-edit.",
        " * Sources: ~/Downloads/pixel--globe(1).png, pixel--folder(1).png,",
        " *          pixel--ellipses-horizontal-circle.png",
        " * A8 alpha only: the app recolours with image_recolor, so one copy",
        " * serves both themes. */",
        "#include \"GamesIcons.h\"",
        "",
    ]
    for name, mask in icons:
        out.append(emit(name, mask))
    open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
